"""번호·기한·보증 판정 규칙. 업무설명_하자보수.md의 2~5절을 그대로 코드로 옮긴 것. AI는 쓰지 않는다."""
import csv
from datetime import date, timedelta
from pathlib import Path

공사정보_경로 = Path(__file__).parent / "data" / "공사정보.csv"

# 업무설명 4절: 긴급도별 조치기한(접수일 + n일)
조치기한_일수 = {"긴급": 1, "높음": 3, "보통": 7}

# 업무설명 5절: 보증내인데 만료까지 이 일수 이내면 만료임박
만료임박_일수 = 30

공사_칸 = ["공사번호", "시공업체", "준공일", "보증만료일"]


def _날짜(값):
    return 값 if isinstance(값, date) else date.fromisoformat(str(값))


def 접수번호(접수일, 순번):
    """HJ-접수일(YYYYMMDD)-순번(01부터). 예: HJ-20261102-01"""
    return f"HJ-{_날짜(접수일):%Y%m%d}-{순번:02d}"


def 조치기한(접수일, 긴급도):
    """접수일 + 긴급 1일 / 높음 3일 / 보통 7일. 모르는 긴급도는 오류."""
    if 긴급도 not in 조치기한_일수:
        raise ValueError(f"긴급도가 긴급·높음·보통이 아닙니다: {긴급도!r}")
    return (_날짜(접수일) + timedelta(days=조치기한_일수[긴급도])).isoformat()


def 공사정보_읽기(경로=공사정보_경로):
    with open(경로, encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def 보증만료일(준공일, 보증기간_년):
    """준공일 + 하자보증기간(년). 윤일(2/29) 준공은 업무설명에 규칙이 없어 2/28로 둔다."""
    준공 = _날짜(준공일)
    년 = 준공.year + int(보증기간_년)
    try:
        return 준공.replace(year=년)
    except ValueError:
        return 준공.replace(year=년, day=28)


def _후보_공종(공종):
    """'설비/타일' -> ['설비', '타일']. 확인필요나 빈 값이면 빈 목록."""
    return [c.strip() for c in str(공종).split("/") if c.strip() and c.strip() != "확인필요"]


def _공사_찾기(위치, 공종목록, 공사목록):
    return [r for r in 공사목록 if r["위치"] == 위치 and r["공종"] in 공종목록]


def 후보공사(위치, 공종, 공사목록=None):
    """위치와 공종이 같은 공사 목록 (화면에서 판정 근거를 보여줄 때 쓴다)."""
    공사목록 = 공사정보_읽기() if 공사목록 is None else 공사목록
    return _공사_찾기(위치, _후보_공종(공종), 공사목록)


def _만료(공사):
    return 보증만료일(공사["준공일"], 공사["하자보증기간(년)"])


def _만료임박(만료일, 접수일):
    return 접수일 <= 만료일 and (만료일 - 접수일).days <= 만료임박_일수


def 보증판정(접수일, 위치, 공종, 공사목록=None):
    """위치와 공종이 모두 같은 공사를 찾아 보증을 판정한다. 기준은 오늘이 아니라 접수일.

    돌려주는 칸: 공사번호, 시공업체, 준공일, 보증만료일, 보증판정, 책임구분, 비고
    - 보증만료일 이전(같은 날 포함) -> 보증내 / 시공업체
    - 보증만료일이 지남 -> 보증만료 / 자체보수
    - 맞는 공사가 없거나 2건 이상, 공종 미정 -> 확인필요 / 확인필요
    - 보증내이고 만료까지 30일 이내 -> 비고 '만료임박'
    - 확인필요 건도 후보 공사가 만료임박이면 비고에 적는다.
    """
    접수 = _날짜(접수일)
    공사목록 = 공사정보_읽기() if 공사목록 is None else 공사목록
    후보 = _후보_공종(공종)
    맞는공사 = _공사_찾기(위치, 후보, 공사목록)

    # 공종이 하나로 정해졌고 맞는 공사가 정확히 1건일 때만 판정한다.
    if len(후보) == 1 and len(맞는공사) == 1:
        공사 = 맞는공사[0]
        만료 = _만료(공사)
        보증내 = 접수 <= 만료
        return {
            "공사번호": 공사["공사번호"],
            "시공업체": 공사["시공업체"],
            "준공일": 공사["준공일"],
            "보증만료일": 만료.isoformat(),
            "보증판정": "보증내" if 보증내 else "보증만료",
            "책임구분": "시공업체" if 보증내 else "자체보수",
            "비고": "만료임박" if _만료임박(만료, 접수) else "",
        }

    # 확인필요: 후보 공사 중 만료임박이 있으면 비고에 함께 적는다.
    임박 = [r["공사번호"] for r in 맞는공사 if _만료임박(_만료(r), 접수)]
    return {
        "공사번호": "", "시공업체": "", "준공일": "", "보증만료일": "",
        "보증판정": "확인필요",
        "책임구분": "확인필요",
        "비고": f"만료임박({', '.join(임박)})" if 임박 else "",
    }
