"""접수함 폴더의 접수 원문을 일괄 처리해 하자대장.csv로 저장한다.

흐름: 원문 읽기 -> AI가 5칸 정리(ai.py) -> 코드가 번호·기한·보증 판정(rules.py) -> CSV 저장
사용: python run.py [입력폴더] [저장파일]
"""
import sys
from collections import defaultdict
from pathlib import Path

import ai
import db
import rules

BASE = Path(__file__).parent
대장_칸 = db.대장_칸


def 행_만들기(파일명, 정리, 순번, 공사목록):
    """AI가 정리한 5칸 + 접수일별 순번 -> 하자대장 1행 (번호·기한·판정은 rules.py)"""
    판정 = rules.보증판정(정리["접수일"], 정리["위치"], 정리["공종"], 공사목록)
    return {
        "접수번호": rules.접수번호(정리["접수일"], 순번),
        "접수일": 정리["접수일"],
        "원문파일": 파일명,
        "위치": 정리["위치"],
        "공종": 정리["공종"],
        "하자내용": 정리["하자내용"],
        "긴급도": 정리["긴급도"],
        "조치기한": rules.조치기한(정리["접수일"], 정리["긴급도"]),
        **판정,
        "상태": "확인필요" if 판정["보증판정"] == "확인필요" else "판정완료",
    }


def 처리(입력폴더, 공사목록):
    순번 = defaultdict(int)  # 접수일별 순번
    행들 = []
    for 파일 in sorted(Path(입력폴더).glob("*.txt")):
        정리 = ai.접수정리(파일.name, 파일.read_text(encoding="utf-8"))
        순번[정리["접수일"]] += 1
        행 = 행_만들기(파일.name, 정리, 순번[정리["접수일"]], 공사목록)
        if len(행["하자내용"]) > 40:
            print(f"[주의] {파일.name}: 하자내용이 40자를 넘습니다({len(행['하자내용'])}자)")
        행들.append(행)
        print(f"{행['접수번호']} {파일.name} -> {행['공종']} / {행['긴급도']} / {행['보증판정']}")
    return 행들


def 접수_원문(접수):
    """DB 접수 한 건을 AI에게 읽힐 글로 만든다."""
    return "\n".join(f"{k}: {접수[k]}" for k in ("발견일", "접수자", "부서", "위치", "내용") if 접수[k])


def DB접수_처리(공사목록):
    """DB의 '미처리' 접수를 하자대장으로 옮기고 처리완료로 바꾼다. 접수일은 발견일을 쓴다."""
    행들 = []
    for 접수 in db.접수_읽기("미처리"):
        이름 = f"DB접수#{접수['id']}"
        if not 접수["발견일"]:
            print(f"[건너뜀] {이름}: 발견일이 없습니다")
            continue
        정리 = ai.접수정리(이름, 접수_원문(접수))
        정리["접수일"] = 접수["발견일"]  # AI가 읽은 날짜 대신 발견일을 접수일로 쓴다
        행 = 행_만들기(이름, 정리, db.다음순번(접수["발견일"]), 공사목록)
        if len(행["하자내용"]) > 40:
            print(f"[주의] {이름}: 하자내용이 40자를 넘습니다({len(행['하자내용'])}자)")
        db.대장_저장([행])  # 한 건씩 저장해야 다음 접수가 이어지는 순번을 받는다
        db.접수_처리완료(접수["id"], 행["접수번호"])
        행들.append(행)
        print(f"{행['접수번호']} {이름} -> {행['공종']} / {행['긴급도']} / {행['보증판정']}")
    return 행들


def 저장(행들, 저장파일=None):
    """하자대장은 DB에 저장한다(db.py). 저장파일은 예전 호출과 맞추려고 남긴 자리이며 쓰지 않는다."""
    db.대장_저장(행들)


if __name__ == "__main__":
    공사 = rules.공사정보_읽기()
    if len(sys.argv) > 1 and sys.argv[1] == "db":  # python run.py db : DB 접수만 처리
        행들 = DB접수_처리(공사)
        print(f"DB 접수 {len(행들)}건을 하자대장에 저장했습니다")
    else:  # python run.py [입력폴더] : 접수함 파일을 처리한 뒤 DB 접수도 처리
        입력 = Path(sys.argv[1]) if len(sys.argv) > 1 else BASE / "data" / "접수함"
        행들 = 처리(입력, 공사)
        저장(행들)
        print(f"접수함 파일 {len(행들)}건을 DB 하자대장에 저장했습니다")
        행들 = DB접수_처리(공사)
        print(f"DB 접수 {len(행들)}건을 하자대장에 저장했습니다")
